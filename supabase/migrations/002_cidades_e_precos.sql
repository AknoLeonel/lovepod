-- Cidades com vendas no histórico não podem ser apagadas sem perder o
-- caixa; elas passam a ser "ocultadas" (somem do site e do PDV).
alter table public.cidades
  add column if not exists ativa boolean not null default true;

-- Apagar uma cidade apaga o estoque dela junto, numa única operação.
-- (Se a cidade tiver vendas, o banco recusa tudo e nada é apagado.)
alter table public.estoque drop constraint if exists estoque_cidade_id_fkey;
alter table public.estoque
  add constraint estoque_cidade_id_fkey
  foreign key (cidade_id) references public.cidades (id) on delete cascade;

-- Preço específico de um produto em uma cidade.
-- Sem linha aqui, vale o preço padrão do produto (produtos.preco).
create table if not exists public.produto_precos (
  id         bigint generated by default as identity primary key,
  produto_id bigint not null references public.produtos (id) on delete cascade,
  cidade_id  bigint not null references public.cidades (id)  on delete cascade,
  preco      numeric(10, 2) not null check (preco >= 0),
  created_at timestamptz not null default now(),
  unique (produto_id, cidade_id)
);
create index if not exists produto_precos_cidade_id_idx on public.produto_precos (cidade_id);

-- Mesmas permissões das outras tabelas (ver aviso em schema.sql)
grant select, insert, update, delete on public.produto_precos to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
alter table public.produto_precos enable row level security;
drop policy if exists acesso_publico on public.produto_precos;
create policy acesso_publico on public.produto_precos
  for all to anon, authenticated using (true) with check (true);
