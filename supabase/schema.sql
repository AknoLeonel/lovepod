-- ---------- Cidades (praças de atuação) ----------
create table public.cidades (
  id         bigint generated by default as identity primary key,
  nome       text not null unique,
  ativa      boolean not null default true, -- false = oculta do site e do PDV
  created_at timestamptz not null default now()
);

-- ---------- Produtos (pods) ----------
create table public.produtos (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  descricao  text,
  preco      numeric(10, 2) not null default 0 check (preco >= 0),
  imagem_url text,
  created_at timestamptz not null default now()
);

-- ---------- Preço do produto em uma cidade ----------
-- Sem linha aqui, vale o preço padrão (produtos.preco).
create table public.produto_precos (
  id         bigint generated by default as identity primary key,
  produto_id bigint not null references public.produtos (id) on delete cascade,
  cidade_id  bigint not null references public.cidades (id)  on delete cascade,
  preco      numeric(10, 2) not null check (preco >= 0),
  created_at timestamptz not null default now(),
  unique (produto_id, cidade_id)
);
create index produto_precos_cidade_id_idx on public.produto_precos (cidade_id);

-- ---------- Sabores (cada um pertence a um produto) ----------
create table public.sabores (
  id         bigint generated by default as identity primary key,
  produto_id bigint not null references public.produtos (id) on delete restrict,
  nome       text not null,
  created_at timestamptz not null default now()
);
create index sabores_produto_id_idx on public.sabores (produto_id);

-- ---------- Estoque (quantidade de um sabor em uma cidade) ----------
create table public.estoque (
  id         bigint generated by default as identity primary key,
  cidade_id  bigint not null references public.cidades (id)  on delete cascade,
  produto_id bigint not null references public.produtos (id) on delete restrict,
  sabor_id   bigint not null references public.sabores (id)  on delete restrict,
  quantidade integer not null default 0 check (quantidade >= 0),
  created_at timestamptz not null default now(),
  unique (cidade_id, produto_id, sabor_id)
);

-- ---------- Vendas ----------
-- valor_total = valor UNITÁRIO realmente cobrado (já com desconto rateado);
-- o total da linha é valor_total * quantidade.
create table public.vendas (
  id               bigint generated by default as identity primary key,
  cidade_id        bigint not null references public.cidades (id)  on delete restrict,
  produto_id       bigint not null references public.produtos (id) on delete restrict,
  sabor_id         bigint not null references public.sabores (id)  on delete restrict,
  vendedor_nome    text not null,
  quantidade       integer not null check (quantidade > 0),
  valor_total      numeric(12, 4) not null,
  metodo_pagamento text not null,
  created_at       timestamptz not null default now()
);
create index vendas_created_at_idx on public.vendas (created_at desc);

-- ---------- Permissões ----------
-- ATENÇÃO: o site atual faz tudo (inclusive admin) com a chave pública,
-- então estas regras liberam leitura e escrita para qualquer um, igual
-- ao banco antigo. Isso precisa ser trocado por Supabase Auth + regras
-- de verdade; por enquanto é o que mantém o site funcionando.
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on all tables in schema public to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

do $$
declare t text;
begin
  foreach t in array array['cidades', 'produtos', 'produto_precos', 'sabores', 'estoque', 'vendas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy acesso_publico on public.%I for all to anon, authenticated using (true) with check (true)', t);
  end loop;
end $$;

